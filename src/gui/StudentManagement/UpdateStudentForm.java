    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       String stuId = txtSearch.getText();
       
       
       
        try {
            
            Student foundStudent = functions.StudentController.searchStudent(stuId);
            
            if (foundStudent == null ) {
                JOptionPane.showMessageDialog(null, "Error: Student ID not Found.");

            } else {
                
                pnlForm.setVisible(true);
                txtNIC.setText(foundStudent.getNic());
                txtName.setText(foundStudent.getName());
                txtSearch.setEditable(false);
                
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

